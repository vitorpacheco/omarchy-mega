function resolve(setting, systemLocale) {
    var value = String(!setting || setting === "auto" ? systemLocale : setting).toLowerCase().split(/[_.@-]/)[0];
    return ["pt", "en", "es"].indexOf(value) >= 0 ? value : "en";
}

function translate(language, source, args) {
    var index = {pt: 0, en: 1, es: 2}[language];
    if (index === undefined) index = 1;
    var result = messages[source] ? (messages[source][index] || messages[source][1] || String(source)) : String(source || "");
    return result.replace(/%([1-9][0-9]*)/g, function(token, n) {
        return args && Number(n) <= args.length ? String(args[Number(n) - 1]) : token;
    });
}

function error(language, source) {
    source = String(source || "");
    var match = /^(storage|transfers|syncs): ([\s\S]*)$/.exec(source);
    if (match) return translate(language, match[1]) + ": " + error(language, match[2]);
    // Upstream diagnostics and unknown sync error codes remain verbatim.
    return translate(language, source);
}
